// Regenerates src/desktop/migrations.ts so the desktop app bundles every migration. Run after adding one.
import { readdirSync, writeFileSync } from 'node:fs';
const files = readdirSync('migrations').filter(f => f.endsWith('.sql')).sort();
const out = ['// Every D1 migration, bundled into the desktop app as text. Generated by scripts/gen-desktop-migrations.mjs;', '// tests/desktop.test.ts checks this list matches the migrations folder.',
  ...files.map((f, i) => `import m${i} from '../../migrations/${f}?raw';`), '',
  `export const MIGRATIONS = [${files.map((f, i) => `{ name: '${f}', sql: m${i} }`).join(', ')}];`, ''].join('\n');
writeFileSync('src/desktop/migrations.ts', out);
console.log(`${files.length} migrations`);
